# 合成済みCloudFormationテンプレートから、コンポーネント別の設計書を生成する。
"""合成済みCloudFormationテンプレートから、コンポーネント別の設計書を生成する。"""

import argparse
import json
from collections import defaultdict
from html import escape
from pathlib import Path
from urllib.parse import quote

TEMPLATE = Path("packages/infra/cdk.out/TsugiteApi.template.json")
OUTPUT = Path("docs/generated/infra")
SIGNATURE = "<!-- Generated by packages.tools.design.infrastructure -->"


def expression(value):
    """単純な参照と文字列結合は、配備時に解決される部分を明示する。"""
    if isinstance(value, str):
        return value
    if not isinstance(value, dict) or len(value) != 1:
        return None
    if isinstance(ref := value.get("Ref"), str):
        return "${Ref:" + ref + "}"
    attr = value.get("Fn::GetAtt")
    if isinstance(attr, list) and len(attr) == 2 and all(isinstance(part, str) for part in attr):
        return "${GetAtt:" + ".".join(attr) + "}"
    join = value.get("Fn::Join")
    if (
        isinstance(join, list)
        and len(join) == 2
        and isinstance(join[0], str)
        and isinstance(join[1], list)
    ):
        parts = [expression(part) for part in join[1]]
        if all(isinstance(part, str) for part in parts):
            return join[0].join(parts)
    return None


def settings(path, value):
    rendered = expression(value)
    if rendered is not None:
        if rendered.lstrip().startswith(("{", "[")):
            try:
                document = json.loads(rendered)
            except json.JSONDecodeError:
                pass
            else:
                yield from settings(path, document)
                return
        yield path, rendered if rendered else "（空文字列）"
    elif isinstance(value, dict) and value:
        for key in sorted(value):
            yield from settings(f"{path}.{key}" if path else key, value[key])
    elif isinstance(value, list) and value:
        for index, item in enumerate(value):
            yield from settings(f"{path}[{index}]", item)
    elif isinstance(value, dict):
        yield path, "（空のオブジェクト）"
    elif isinstance(value, list):
        yield path, "（空の配列）"
    else:
        yield path, json.dumps(value, allow_nan=False)


def cell(value):
    """Markdown表の中でもパイプ・改行・バッククォートを値として表示する。"""
    if value and value == value.strip() and not any(char in value for char in "\n\r`|"):
        return f"`{value}`"
    lines = []
    for line in value.split("\n"):
        escaped = escape(line, quote=False)
        for char in "\\|`*_[]~":
            escaped = escaped.replace(char, f"&#{ord(char)};")
        lines.append(escaped)
    return "<code>" + "<br>".join(lines) + "</code>"


def write_page(target, lines):
    target.write_text(SIGNATURE + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def generate(template, out=OUTPUT):
    resources = json.loads(template.read_text(encoding="utf-8"))["Resources"]
    groups = defaultdict(list)
    for logical_id, resource in sorted(resources.items()):
        component = resource.get("Metadata", {}).get("Tsugite", {}).get("Component")
        if not isinstance(component, str) or not component:
            raise ValueError(f"{logical_id}: Metadata.Tsugite.Component がありません")
        groups[component].append((logical_id, resource))

    out.mkdir(parents=True, exist_ok=True)
    index = [
        "# インフラ設計書",
        "",
        f"対象テンプレート `{template.name}`。全{len(groups)}コンポーネント、{len(resources)}リソース。",
        "",
        "| コンポーネント | リソース数 |",
        "| --- | ---: |",
    ]
    files = set()
    for component, entries in sorted(groups.items()):
        filename = "component-" + quote(component, safe="") + ".md"
        files.add(filename)
        index.append(f"| [{cell(component)}]({quote(filename)}) | {len(entries)} |")
        lines = [
            f"# {component} のインフラ設計",
            "",
            "[コンポーネント一覧](README.md)",
            "",
            "## リソース一覧",
            "",
            "| 論理ID | リソースタイプ | CDKの構成パス |",
            "| --- | --- | --- |",
        ]
        for logical_id, resource in entries:
            construct = resource["Metadata"].get("aws:cdk:path")
            lines.append(
                f"| [{logical_id}](#{logical_id.lower()}) | {resource['Type']} | {cell(construct) if construct else '—'} |"
            )
        lines.extend(
            [
                "",
                "## パラメーターシート",
                "",
                "項目名はCloudFormationの階層、配列の添字は0始まりです。"
                "`${Ref:…}` と `${GetAtt:…}` は配備時に解決される参照を示します。",
            ]
        )
        for logical_id, resource in entries:
            lines.extend(["", f"### {logical_id}", "", "| 設定項目 | 設定値 |", "| --- | --- |"])
            for key in sorted(resource.keys() - {"Type"}):
                for path, value in settings(key, resource[key]):
                    lines.append(f"| {cell(path)} | {cell(value)} |")
        write_page(out / filename, lines)
    write_page(out / "README.md", index)
    for page in out.glob("component-*.md"):
        if page.name not in files and page.read_text(encoding="utf-8").startswith(SIGNATURE + "\n"):
            page.unlink()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template", type=Path, default=TEMPLATE)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args()
    generate(args.template, args.out)
