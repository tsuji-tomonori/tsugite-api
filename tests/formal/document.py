"""Quintのドキュメントコメントからドメインと不変条件の一覧を生成する。"""

import argparse
import json
import os
import subprocess
from pathlib import Path
from tempfile import TemporaryDirectory

FORMAL = Path(__file__).resolve().parent
DOCUMENT = FORMAL.parents[1] / "docs/generated/formal/domains.md"
INVARIANT = "safe"


def documentation(node, definition):
    """定義に付いたQuintのドキュメントコメントを取り出す。"""
    doc = node.get("doc", "").strip()
    if not doc:
        raise ValueError(f"{definition} の直前に /// で日本語の説明を記述してください")
    return doc


def cell(text):
    """複数行のコメントをMarkdown表の一つのセルに収める。"""
    return " ".join(text.split()).replace("|", r"\|")


def model_row(quint, model, work, document):
    """QuintのJSONとソースマップから一つのモデルの行を組み立てる。"""
    ir = work / "model.json"
    source_map = work / "source-map.json"
    subprocess.run([quint, "parse", model, "--out", ir, "--source-map", source_map], check=True)
    modules = json.loads(ir.read_text(encoding="utf-8"))["modules"]
    module = next((item for item in modules if item["name"] == model.stem), None)
    if module is None:
        raise ValueError(f"{model.name}: ファイル名と同じ名前のモジュールが必要です")
    invariant = next(
        (
            item
            for item in module["declarations"]
            if item.get("name") == INVARIANT and item.get("qualifier") in {"val", "pureval"}
        ),
        None,
    )
    if invariant is None:
        raise ValueError(f"{model.name}: TLCが検査する {INVARIANT} の定義が必要です")

    title, _, scope = documentation(module, model.name).partition("\n")
    if not scope.strip():
        raise ValueError(f"{model.name}: モジュールの和名に続けてモデルの対象を記述してください")
    rule = documentation(invariant, f"{model.name} の {INVARIANT}")
    locations = json.loads(source_map.read_text(encoding="utf-8"))["map"]
    line = locations[str(invariant["id"])][1]["line"] + 1
    source = Path(os.path.relpath(model, document.parent)).as_posix()
    return (
        f"| {cell(title)} | {cell(scope)} | {cell(rule)} | "
        f"[`{module['name']}.{INVARIANT}`]({source}#L{line}) |"
    )


def render(quint, models, document):
    """定義元へのリンクとともに、全モデルの和名と検査条件を一覧にする。"""
    with TemporaryDirectory() as tmp:
        rows = [model_row(quint, model, Path(tmp), document) for model in models]
    if not rows:
        raise ValueError("文書化するQuintモデルがありません")
    return "\n".join(
        [
            "<!-- Generated by tests/formal/document.py. -->",
            "",
            "# 継手APIのドメインと不変条件",
            "",
            f"Quintで表した{len(rows)}件の業務モデルを掲載します。"
            "不変条件は、モデルの初期状態から到達できるすべての状態で成立すべき条件です。"
            "TLCは各モデルに定義された有限の範囲を検査します。",
            "",
            "| ドメイン | モデルの対象 | 不変条件 | Quintの定義 |",
            "| --- | --- | --- | --- |",
            *rows,
            "",
        ]
    )


def main():
    """文書を再生成し、CIではコミット済みの内容と照合する。"""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quint", default=FORMAL / "node_modules/.bin/quint")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = render(args.quint, sorted(FORMAL.glob("*.qnt")), DOCUMENT)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
    if args.check:
        if not DOCUMENT.is_file() or DOCUMENT.read_text(encoding="utf-8") != generated:
            raise SystemExit("形式仕様の文書に差分があります。task docs:formal で再生成してください")
    else:
        DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
        DOCUMENT.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
