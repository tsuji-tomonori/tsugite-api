OUT = ROOT / "docs/generated"
SIGNATURE = "<!-- Generated by task docs. -->"
METHODS = {"get", "post", "put", "patch", "delete", "options", "head", "trace"}


def grid(headers, rows):
    def line(row):
        return (
            "| " + " | ".join(str(cell).replace("|", r"\|").replace("\n", "<br>") for cell in row) + " |"
        )

    return [line(headers), line(["---"] * len(headers)), *(line(row) for row in rows)]


def encoded(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(", ", ": "))


def reference(spec, obj):
    seen = set()
    while isinstance(obj, dict) and (ref := obj.get("$ref", "")).startswith("#/") and ref not in seen:
        seen.add(ref)
        obj = spec
        for part in ref[2:].split("/"):
            obj = obj[part.replace("~1", "/").replace("~0", "~")]
    return obj


def schema_label(schema):
    if not schema:
        return "型の指定なし"
    if isinstance(schema, dict) and "$ref" in schema:
        model = schema["$ref"].rsplit("/", 1)[-1]
        return f"[{model}](../schemas.md#{model.lower()})"
    if isinstance(schema, dict) and schema.get("type") == "array":
        return "配列 / " + schema_label(schema.get("items", {}))
    return "`" + encoded(schema) + "`"


def dependencies(dep):
    yield dep.call
    for child in dep.dependencies:
        yield from dependencies(child)


def symbol(call):
    obj = inspect.unwrap(call) if inspect.isroutine(call) else call
    return (
        getattr(obj, "__module__", "")
        + "."
        + getattr(obj, "__qualname__", "").replace(".<locals>.", ".")
    )


def catalog(demo):
    with patch.dict(os.environ, {"TSUGITE_DEMO": "1" if demo else "0", "AWS_LAMBDA_FUNCTION_NAME": ""}):
        app = create_app()
        schema = app.openapi()
        records = {}
        for route in iter_route_contexts(app.routes):
            if not isinstance(route.original_route, APIRoute):
                continue
            path = route.path_format
            for method in sorted(route.methods):
                op = schema["paths"].get(path, {}).get(method.lower())
                if op is None:
                    # Standalone route keeps the runtime app's publication settings intact.
                    router = APIRouter()
                    router.add_api_route(
                        route.path,
                        route.endpoint,
                        methods=[method],
                        dependencies=route.dependencies,
                        response_model=route.response_model,
                        responses=route.responses,
                        status_code=route.status_code,
                        openapi_extra=route.openapi_extra,
                    )
                    hidden = get_openapi(title="design", version="1", routes=router.routes)
                    op = hidden["paths"][path][method.lower()]
                    for kind, entries in hidden.get("components", {}).items():
                        schema.setdefault("components", {}).setdefault(kind, {}).update(entries)
                records[(path, method)] = (route, op)
    return schema, records


def security(spec, op):
    if "x-design-auth" in op:
        return op["x-design-auth"]
    choices = []
    for group in op.get("security", spec.get("security", [])):
        schemes = []
        for key, scopes in group.items():
            scheme = reference(spec, spec["components"]["securitySchemes"][key])
            if scheme.get("type") == "http":
                desc = f"Authorization: {scheme['scheme'].title()} <資格情報>"
            elif scheme.get("type") == "apiKey":
                desc = f"{scheme['in']} の {scheme['name']}"
            else:
                desc = f"{scheme['type']} {', '.join(scopes)}"
            schemes.append(desc)
        choices.append(" ＋ ".join(schemes) or "認証不要")
    return " または ".join(choices) or "認証不要"


def fields(spec, schema, path="", parents=()):
    schema = reference(spec, schema)
    if not isinstance(schema, dict) or id(schema) in parents:
        return
    chain = (*parents, id(schema))
    if schema.get("type") == "array":
        yield from fields(spec, schema.get("items"), path + "[]", chain)
    for group in ("anyOf", "oneOf", "allOf"):
        for variant in schema.get(group, []):
            prefix = variant.get("$ref", "").rsplit("/", 1)[-1]
            yield from fields(spec, variant, f"{path}({prefix})" if prefix else path, chain)
    for key, child in schema.get("properties", {}).items():
        field = f"{path}.{key}" if path else key
        yield (field, "必須" if key in schema.get("required", []) else "任意", schema_label(child))
        yield from fields(spec, child, field, chain)


def field_table(spec, media, heading):
    rows = list(fields(spec, media.get("schema")))
    return ["", heading, "", *grid(["項目", "指定", "型・制約"], rows)] if rows else []


def contract(spec, path, op):
    lines = ["## 入力", "", f"**認証**　{security(spec, op)}", ""]
    params = {}
    for raw in [*spec["paths"].get(path, {}).get("parameters", []), *op.get("parameters", [])]:
        p = reference(spec, raw)
        params[p["in"], p["name"]] = p
    if params:
        rows = []
        for (where, key), p in params.items():
            style = p.get("style", "form" if where in {"query", "cookie"} else "simple")
            explode = p.get("explode", style == "form")
            rows.append(
                (
                    where,
                    key,
                    "必須" if p.get("required") else "任意",
                    schema_label(p.get("schema", p.get("content"))),
                    f"{style} / {str(explode).lower()}",
                    p.get("description", "—"),
                )
            )
        lines += grid(["場所", "名前", "指定", "型・制約", "style / explode", "説明"], rows)
    else:
        lines.append("入力パラメータなし。")
    body = reference(spec, op.get("requestBody", {}))
    lines += ["", "### リクエストボディ", ""]
    if op.get("x-design-proxy"):
        lines.append(
            "クエリ文字列とボディを転送します。項目、形式、必須条件は登録された転送先のOpenAPIを参照してください。"
        )
    elif body:
        lines += ["必須。" if body.get("required") else "任意。", ""]
        lines += grid(
            ["Content-Type", "スキーマ"],
            [(k, schema_label(v.get("schema"))) for k, v in body.get("content", {}).items()],
        )
        for kind, media in body.get("content", {}).items():
            lines += field_table(spec, media, f"#### {kind} の項目")
    else:
        lines.append("なし。")
    lines += ["", "## レスポンス", ""]
    rows = []
    for code, raw in op.get("responses", {}).items():
        r = reference(spec, raw)
        if op.get("x-design-proxy") and code == "200":
            rows.append(
                (
                    "転送先による",
                    "転送先のHTTPステータスとボディ",
                    "転送先のContent-Typeに応じて決定",
                    "転送先の定義を参照",
                )
            )
            continue
        for media, data in (r.get("content") or {"—": {}}).items():
            rows.append(
                (
                    code,
                    r.get("description", ""),
                    media,
                    schema_label(data.get("schema")) if media != "—" else "なし",
                )
            )
        for key, value in r.get("headers", {}).items():
            hdr = reference(spec, value)
            rows.append(
                (
                    code,
                    "応答ヘッダー " + key,
                    hdr.get("description", ""),
                    schema_label(hdr.get("schema")),
                )
            )
    lines += grid(["ステータス", "説明", "形式・条件", "スキーマ"], rows)
    for code, raw in op.get("responses", {}).items():
        for media, data in reference(spec, raw).get("content", {}).items():
            lines += field_table(spec, data, f"### {code} {media} の項目")
    return lines


def source_link(index, func, line):
    path = index.paths[func].relative_to(ROOT).as_posix()
    return f"[{func.rsplit('.', 1)[-1]}:{line}](../../../{path}#L{line})"


def generate(out=OUT):
    spec, records = catalog(True)
    demo_routes = set(records)
    prod_spec, production = catalog(False)
    for key, route in production.items():
        if key not in records:
            records[key] = route
            spec["paths"].setdefault(key[0], {}).update(prod_spec["paths"].get(key[0], {}))
    for group, entries in prod_spec.get("components", {}).items():
        for key, definition in entries.items():
            spec["components"].setdefault(group, {}).setdefault(key, definition)
    index = SourceIndex()
    pages = {}
    overview = []
    crud = []
    for (path, method), (route, op) in sorted(records.items()):
        filename = method.lower() + "-" + re.sub(r"[^\w.-]+", "-", path).strip("-") + ".md"
        dest = "apis/" + filename
        if dest in pages:
            raise ValueError(f"ページ名が重複しました {dest}")
        link = f"[{method} `{path}`]({dest})"
        scope = (
            "デモ限定"
            if (path, method) not in production
            else "本番限定"
            if (path, method) not in demo_routes
            else "共通"
            if route.include_in_schema
            else "転送用（公開スキーマ外）"
        )
        overview.append((link, scope, op["operationId"], security(spec, op)))
        facts = index.trace(symbol(fn) for fn in dependencies(route.dependant))
        handler = symbol(route.endpoint)
        lines = [
            f"# {method} `{path}`",
            "",
            "[API一覧](../README.md) · [CRUD一覧](../crud.md)",
            "",
            f"{scope} · `{op['operationId']}` · "
            + source_link(index, handler, index.functions[handler].lineno),
            "",
        ]
        if op.get("description"):
            lines.extend([op["description"], ""])
        lines += contract(spec, path, op)
        if facts.status:
            lines += [
                "",
                "実装・認証依存で送出し得るHTTPエラー（detailを含むJSON）　"
                + ", ".join(map(str, sorted(facts.status)))
                + "。",
            ]
        lines += [
            "",
            "AWS環境ではCloudFrontが内部ヘッダー `X-Tsugite-Origin` を付与します。共通ミドルウェアは通常のAPI応答に `X-Request-ID` と `Cache-Control: no-store` を付けます。Lambdaのオリジン検証に失敗すると403、DBの競合は409、DB操作エラーは409または503です。",
        ]
        if not op.get("x-design-proxy") and any(
            v.get("schema") == {}
            for resp in op.get("responses", {}).values()
            for v in resp.get("content", {}).values()
        ):
            returns = [
                ast.unparse(n.value)
                for n in body_nodes(index.functions[handler])
                if isinstance(n, ast.Return) and n.value is not None
            ]
            if returns:
                lines += [
                    "",
                    "### 実装の戻り値",
                    "",
                    "OpenAPIで型を指定していない応答のreturn式です。",
                    "",
                    "```python",
                    *returns,
                    "```",
                ]
        lines += ["", "## SQL・AWSの操作", ""]
        grouped = defaultdict(set)
        evidence = []
        for kind, resource, action, func, line, detail in sorted(facts.effects):
            grouped[kind, resource].add(action)
            evidence.append((kind, resource, action, detail, source_link(index, func, line)))
        lines += (
            grid(["種別", "対象", "操作", "実装", "根拠"], evidence)
            if evidence
            else ["該当する操作を検出しませんでした。"]
        )
        for func, line, reason in sorted(facts.unresolved):
            lines += ["", f"要確認　{reason}　" + source_link(index, func, line)]
        lines += [
            "",
            "<details><summary>解析した関数・依存</summary>",
            "",
            *["- `" + f + "`" for f in sorted(facts.calls)],
            "",
            "</details>",
        ]
        crud.append(
            (
                link,
                *[
                    "、".join(
                        f"{res} ({'/'.join(sorted(ops))})"
                        for (k, res), ops in sorted(grouped.items())
                        if k == kind
                    )
                    or "—"
                    for kind in ("SQL", "AWS")
                ],
                len(facts.unresolved),
            )
        )
        pages[dest] = lines
    with patch.dict(os.environ, {"TSUGITE_DEMO": "1", "AWS_LAMBDA_FUNCTION_NAME": ""}):
        schema_url = create_app().openapi_url
    pages["README.md"] = [
        "# API実装設計書",
        "",
        f"{len(records)}操作。[SQL・AWS CRUD一覧](crud.md) · [入出力スキーマ](schemas.md)",
        "",
        "FastAPIに登録された業務ルートをメソッド別に掲載します。認証条件・入力・応答・呼び出し先は各操作を開いて確認できます。",
        "",
        *grid(["操作", "利用環境", "operationId", "認証"], overview),
        "",
        "## FastAPIのスキーマ配信",
        "",
        f"デモ環境の `GET {schema_url}` は認証・パラメータ・ボディ不要です。200 application/jsonでOpenAPI文書を返します。SQL・AWS操作はありません。",
    ]
    pages["crud.md"] = [
        "# API別 SQL・AWS CRUD一覧",
        "",
        "SQLテーブルはAWS環境ではAurora DSQL、ローカルデモではSQLiteを使います。C＝作成、R＝参照、U＝更新、D＝削除。LambdaのInvokeは「実行」です。認証依存、条件分岐、失敗時の補償処理を含む到達可能な操作を示します。実行順・実行回数は表しません。各操作のリンクから根拠の実装行を確認できます。",
        "",
        "静的解析ではSQLAlchemyの式・ORM属性の代入・リテラルSQL、boto3クライアントの呼び出しを追跡します。動的なディスパッチ、外部ライブラリ内部のSQL・AWS操作は解析範囲外です。",
        "",
        *grid(["操作", "SQLテーブル", "AWSサービス", "要確認件数"], crud),
    ]
    lines = ["# 入出力スキーマ", "", "[API一覧](README.md)"]
    for key, schema in sorted(spec["components"].get("schemas", {}).items()):
        lines += ["", f"## {key}", ""]
        if props := schema.get("properties"):
            lines += grid(
                ["項目", "指定", "型・制約"],
                [
                    (
                        k,
                        "必須" if k in schema.get("required", []) else "任意",
                        schema_label(v).replace("../schemas.md#", "#"),
                    )
                    for k, v in props.items()
                ],
            )
        lines += [
            "",
            "<details><summary>JSON Schema</summary>",
            "",
            "```json",
            json.dumps(schema, indent=2, ensure_ascii=False, sort_keys=True),
            "```",
            "",
            "</details>",
        ]
    pages["schemas.md"] = lines
    out = Path(out)
    for dest, lines in pages.items():
        target = out / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            SIGNATURE + "\n\n" + "\n".join(lines).strip() + "\n", encoding="utf-8", newline="\n"
        )
    for file in (out / "apis").glob("*.md"):
        if file.relative_to(out).as_posix() not in pages and file.read_text(encoding="utf-8").startswith(
            SIGNATURE + "\n"
        ):
            file.unlink()


if __name__ == "__main__":
    generate()
